def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--upstream", type=Path, default=ROOT / "vendor/branding-base")
    args = parser.parse_args()
    spec = json.loads((ROOT / "branding/brand.json").read_text(encoding="utf-8"))
    reference = (ROOT / spec["reference_image"]).read_bytes()
    with Image.open(ROOT / spec["reference_image"]) as image:
        pixels = terminal_pixels(image.convert("RGB"), spec)
    updated_logo = source(spec, pixels)
    write(ROOT / "branding/logo.tsx", updated_logo)
    write(ROOT / "branding/mark.json", json.dumps(pixels, indent=2) + "\n")
    patch = ""
    changes = {"packages/tui/src/component/logo.tsx": updated_logo}
    home_path = "packages/tui/src/routes/home.tsx"
    home = (args.upstream / home_path).read_text(encoding="utf-8")
    old = 'normal: ["Fix a TODO in the codebase", "What is the tech stack of this project?", "Fix broken tests"]'
    if home.count(old) != 1:
        raise ValueError("Pinned home placeholder context changed")
    changes[home_path] = home.replace(old, "normal: " + json.dumps(spec["placeholders"], ensure_ascii=False))
    for filename, updated in changes.items():
        original = (args.upstream / filename).read_text(encoding="utf-8")
        patch += "diff --git a/%s b/%s\n" % (filename, filename)
        patch += "".join(difflib.unified_diff(original.splitlines(True), updated.splitlines(True), fromfile="a/" + filename, tofile="b/" + filename))
    write(ROOT / "patches/0002-xunchi-home-branding.patch", patch)
    write(ROOT / "branding/startup-preview.html", preview(spec, pixels, reference))
    provenance = {"reference_sha256": hashlib.sha256(reference).hexdigest(), "mark_region": spec["mark_region"],
                  "terminal_rendition": "two-color half-block approximation; not a replacement original logo",
                  "source_patch": "0002-xunchi-home-branding.patch", "deployment_status": "not_built_not_deployed"}
    write(ROOT / "branding/provenance.json", json.dumps(provenance, ensure_ascii=False, indent=2) + "\n")
    print("Generated branding source, patch and static preview. Engine not built or deployed.")


if __name__ == "__main__":
    main()
