#!/usr/bin/env python3
"""Build terminal brand source and a browser preview from the supplied logo.

Development dependency: Pillow. Product startup does not require Pillow.
The reference image is read only and is never rewritten.
"""
import argparse
import base64
import difflib
import hashlib
import html
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)


def terminal_pixels(image, spec):
    left, top, right, bottom = spec["mark_region"]
    cols, rows = spec["mark_columns"], spec["mark_pixel_rows"]
    result = []
    for y in range(rows):
        row = ""
        y0, y1 = top + y * (bottom - top) // rows, top + (y + 1) * (bottom - top) // rows
        for x in range(cols):
            x0, x1 = left + x * (right - left) // cols, left + (x + 1) * (right - left) // cols
            samples = [image.getpixel((xx, yy))[:3] for yy in range(y0, y1) for xx in range(x0, x1)]
            blue = [(r, g, b) for r, g, b in samples if b > 100 and g > 65 and b > 1.7 * max(r, 1)]
            if len(blue) < 0.35 * len(samples):
                row += "."
            else:
                row += "c" if sum(p[1] for p in blue) / len(blue) > 140 else "b"
        result.append(row)
    return result


